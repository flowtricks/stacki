// The config for the preview servers that run without the canvas's own (preview/markerConfig.ts): an
// older version's preview and a thumbnail's temporary server. It is the project's config plus one
// Vite plugin, so their images are not kept for a year under a name that will hold other pictures
// (previewServer/previewImageCache.ts). Written under node_modules/.avb, never over a project file.

import fs from 'fs';
import path from 'path';
import { assert } from '../../shared/core/assert';
import { RUNTIME_PATHS } from '../lib/runtimePaths';
import { ASTRO_CONFIG_FILES, parsesAsModule } from './devServerChecks';

const FILE_NAME = 'image-cache.astro.config.mjs';

/** The generated module. `userConfig`: the project's config file name, or undefined when it has none. */
export function renderImageCacheConfig(userConfig: string | undefined, pluginPath: string): string {
  assert(pluginPath.length > 0, 'renderImageCacheConfig: the plugin has a path');
  const source = [
    '// Generated by Stacki (dev preview only) — do not edit.',
    "import { createRequire } from 'node:module';",
    userConfig === undefined ? 'const userConfig = {};' : `import userConfig from ${JSON.stringify(`../../${userConfig}`)};`,
    `const { previewImageCachePlugin } = createRequire(import.meta.url)(${JSON.stringify(pluginPath)});`,
    'const base = userConfig || {};',
    'export default {',
    '  ...base,',
    '  vite: {',
    '    ...(base.vite || {}),',
    '    plugins: [previewImageCachePlugin(base.image), ...((base.vite && base.vite.plugins) || [])],',
    '  },',
    '};',
    '',
  ].join('\n');
  assert(source.startsWith('// Generated by Stacki'), 'renderImageCacheConfig: the header is kept');
  return source;
}

/**
 * Writes the config into `directory` (a project, or a checkout of one) and answers with astro's
 * `--config` arguments for it. Empty when it cannot be written or will not parse: the server then
 * runs on the project's own config, as it did before.
 */
export function imageCacheConfigArgs(directory: string): readonly string[] {
  try {
    const folder = path.join(directory, 'node_modules', '.avb');
    fs.mkdirSync(folder, { recursive: true });
    const userConfig = ASTRO_CONFIG_FILES.find((name) => fs.existsSync(path.join(directory, name)));
    const file = path.join(folder, FILE_NAME);
    fs.writeFileSync(file, renderImageCacheConfig(userConfig, RUNTIME_PATHS.previewImageCache));
    if (!parsesAsModule(file)) {
      return [];
    }
    // Astro resolves --config against the project root and rejects an absolute path.
    return ['--config', `node_modules/.avb/${FILE_NAME}`];
  } catch (error: unknown) {
    console.warn('[preview] the image cache config was not written:', error instanceof Error ? error.message : String(error));
    return [];
  }
}
