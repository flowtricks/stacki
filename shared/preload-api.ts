type InvokeSurface = {
  readonly [Method in keyof InvokeChannels]: (
    ...args: undefined extends IpcPayloads[InvokeChannels[Method]]
      ? [payload?: IpcPayloads[InvokeChannels[Method]]]
      : [payload: IpcPayloads[InvokeChannels[Method]]]
  ) => Promise<unknown>;
};

