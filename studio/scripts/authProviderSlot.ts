// Build step: wire the instance's custom authentication provider in, or the built-in GitHub one.
// A Worker cannot pick a module at runtime, so the choice is made here, at build time, by writing the one-line
// slot module the Worker imports (src/cloudflare/authProviderSlot.ts). `studio/cloudflare/` survives Studio updates
// (retainedPath in shared/ipc/studioRelease.ts), so a provider kept there is still installed after one.
//
//   studio/cloudflare/auth-provider.ts exists  ->  the slot re-exports its default export, and the build type-checks
//                                                  it against the interface and stops, loudly, if it does not fit
//   no such file                               ->  the slot says "no custom provider": GitHub sign-in, unchanged
import { spawnSync } from 'node:child_process';
import { access, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const AUTH_PROVIDER_FILE = 'cloudflare/auth-provider.ts';
export const SLOT_FILE = 'src/cloudflare/authProviderSlot.ts';
// A type-check of the Worker's sources; bounded so a hung compiler fails the build instead of waiting forever.
const TYPE_CHECK_TIMEOUT_MS = 300_000;

export type AuthProviderSelection = 'built-in' | 'custom';

/** The exact text of the slot module for a selection. */
export function authProviderSlotSource(selection: AuthProviderSelection): string {
  const comment = [
    '// Which custom authentication provider this instance installed, if any. GENERATED by scripts/authProviderSlot.ts on',
    '// every `npm run build`: with no `studio/cloudflare/auth-provider.ts` it is the file below (GitHub sign-in, the',
    "// default); with one, it re-exports that file's default export. A Worker cannot choose a module at runtime, so the",
    '// choice is made at build time, and the build refuses a provider that does not type-check against the interface.',
    '// Do not edit by hand: the next build rewrites it. See docs/auth-providers.md.',
  ];
  const imports = ["import type { AuthProviderFactory } from '../features/auth/authProvider';"];
  if (selection === 'custom') {
    imports.push("import custom from '../../cloudflare/auth-provider';");
  }
  const value = selection === 'custom' ? 'custom' : 'undefined';
  return [...comment, ...imports, '', `export const customAuthProvider: AuthProviderFactory | undefined = ${value};`, ''].join('\n');
}

export async function prepareAuthProvider(studio: string = fileURLToPath(new URL('../', import.meta.url))): Promise<AuthProviderSelection> {
  const custom = await access(path.join(studio, AUTH_PROVIDER_FILE)).then(
    () => true,
    () => false,
  );
  const selection: AuthProviderSelection = custom ? 'custom' : 'built-in';
  const slot = path.join(studio, SLOT_FILE);
  const wanted = authProviderSlotSource(selection);
  const current = await readFile(slot, 'utf8').catch(() => '');
  if (current !== wanted) {
    await writeFile(slot, wanted);
  }
  if (selection === 'custom') {
    assertSatisfiesInterface(studio);
  }
  return selection;
}

function assertSatisfiesInterface(studio: string): void {
  const compiler = path.join(studio, 'node_modules/.bin/tsc');
  const result = spawnSync(compiler, ['-p', 'tsconfig.worker.json', '--noEmit', '--pretty', 'false'], {
    cwd: studio,
    encoding: 'utf8',
    timeout: TYPE_CHECK_TIMEOUT_MS,
  });
  if (result.status !== 0) {
    throw new Error(
      `studio/${AUTH_PROVIDER_FILE} does not satisfy the AuthProvider interface (docs/auth-providers.md).\n` +
        'Its default export must be an AuthProviderFactory. Fix these errors, or remove the file to sign in with GitHub:\n' +
        (result.stdout + result.stderr).trim().slice(0, 4000),
    );
  }
}
