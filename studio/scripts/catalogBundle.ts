// Each interface language ships as one catalog file instead of one per namespace.
//
// Why: Desktop and every Studio already installed refuse a release of more than 3,000 files
// (RELEASE_FILES_MAX, fixed in their code), and 18 languages of 44 namespace files each were 792
// of them. The Stacki source keeps one file per namespace; only the assembled copy is merged. A
// language's `index.ts` holds every message inline. A namespace that Studio imports on its own
// (STANDALONE_NAMESPACES) stays a file of its own, and the index spreads it.
//
// The types survive the merge: English's keys still define `MessageKey`, and every other language
// still `satisfies CatalogOf<MessageKey>`, so a missing or unknown key fails Studio's type check,
// in an installed project too.
//
// This module runs only where the Stacki source is (assemble.ts). It ships because assemble.ts
// does, so it imports nothing from outside Studio.
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { record, string } from '../src/shared/primitiveValidation';

export const CATALOG_ROOT = 'shared/properties/i18n/messages/';

/** Namespaces that code outside the language's index imports (src/shared/requestTranslate.ts). */
export const STANDALONE_NAMESPACES = ['studio'] as const satisfies readonly string[];

export const CATALOG_BUNDLE_LIMITS = {
  filesMax: 2_000,
  messagesMax: 20_000,
  // What an installed client accepts for one release file (shared/ipc/studioRelease.ts).
  bundleCharsMax: 2_000_000,
} as const satisfies Record<string, number>;

type Messages = ReadonlyMap<string, unknown>;

export interface CatalogPlan {
  /** The inventory files still copied one by one. */
  readonly files: readonly string[];
  /** The generated language indexes, by inventory path. */
  readonly bundles: ReadonlyMap<string, string>;
}

/** Splits the inventory into the files to copy and the merged language indexes that stand for the rest. */
export async function planCatalogs(root: string, inventory: readonly string[]): Promise<CatalogPlan> {
  assert(inventory.length > 0, 'An inventory lists files');
  const locales = new Map<string, string[]>();
  const files: string[] = [];
  for (const file of inventory) {
    const match = file.startsWith(CATALOG_ROOT) ? /^([A-Za-z]+)\/([A-Za-z]+)\.ts$/.exec(file.slice(CATALOG_ROOT.length)) : null;
    const locale = match?.[1];
    const namespace = match?.[2];
    if (locale === undefined || namespace === undefined) {
      files.push(file);
      continue;
    }
    const namespaces = locales.get(locale) ?? [];
    namespaces.push(namespace);
    locales.set(locale, namespaces);
    if (STANDALONE_NAMESPACES.some((name) => name === namespace)) {
      files.push(file);
    }
  }
  assert(inventory.length <= CATALOG_BUNDLE_LIMITS.filesMax + files.length, 'Catalog files stay bounded');
  const bundles = new Map<string, string>();
  for (const [locale, namespaces] of locales) {
    // A language without an index has nothing to merge into: that is a broken inventory.
    assert(namespaces.includes('index'), `The shared source inventory lists ${locale} catalogs without their index`);
    bundles.set(`${CATALOG_ROOT}${locale}/index.ts`, await bundleLocale(root, locale, namespaces));
  }
  return { files, bundles };
}

async function bundleLocale(root: string, locale: string, namespaces: readonly string[]): Promise<string> {
  const folder = path.join(root, CATALOG_ROOT, locale);
  const merged = await readMessages(path.join(folder, 'index.ts'));
  const standalone = STANDALONE_NAMESPACES.filter((name) => namespaces.includes(name));
  const spread = new Set<string>();
  for (const name of standalone) {
    for (const [key, value] of await readMessages(path.join(folder, `${name}.ts`))) {
      assert(merged.get(key) !== undefined, `${locale}/index.ts must hold every key of ${locale}/${name}.ts: ${key}`);
      assert(JSON.stringify(merged.get(key)) === JSON.stringify(value), `${locale}/index.ts changes ${locale}/${name}.ts: ${key}`);
      spread.add(key);
    }
  }
  const text = catalogSource(
    locale,
    standalone,
    [...merged].filter(([key]) => !spread.has(key)),
  );
  assert(text.length <= CATALOG_BUNDLE_LIMITS.bundleCharsMax, `The ${locale} catalog is larger than one release file may be`);
  return text;
}

function catalogSource(locale: string, standalone: readonly string[], entries: readonly (readonly [string, unknown])[]): string {
  const english = locale === 'en';
  return [
    `// Generated by Stacki's assemble step: every namespace of the ${locale} catalog, merged (scripts/catalogBundle.ts).`,
    "import type { CatalogOf } from '../../../../core/i18n/catalog';",
    ...(english ? [] : ["import type { MessageKey } from '../en/index';"]),
    ...standalone.map((name) => `import { messages as ${name} } from './${name}';`),
    '',
    'export const messages = {',
    ...entries.map(([key, value]) => `  ${quoted(key)}: ${literal(value)},`),
    ...standalone.map((name) => `  ...${name},`),
    `} as const satisfies CatalogOf<${english ? 'string' : 'MessageKey'}>;`,
    ...(english ? ['', 'export type MessageKey = keyof typeof messages;'] : []),
    '',
  ].join('\n');
}

function literal(value: unknown): string {
  if (typeof value === 'string') {
    return quoted(value);
  }
  const forms = Object.entries(record(value)).map(([form, text]) => `${quoted(form)}: ${literal(text)}`);
  return `{ ${forms.join(', ')} }`;
}

// Single quotes, because the release file is JSON: every double quote would be stored as two bytes, and installed
// clients bound the file's size too (RELEASE_BYTES_MAX). JSON's escapes are TypeScript's; only the quotes swap.
function quoted(text: string): string {
  const escaped = JSON.stringify(text)
    .slice(1, -1)
    .replace(/\\(.)/g, (pair, next: string) => (next === '"' ? '"' : pair))
    .replaceAll("'", "\\'");
  return `'${escaped}'`;
}

// The catalog module's `messages`, checked: a message is a string or plural forms, all of them strings. The Stacki root
// is CommonJS, so the loader may hand its named export over under `default`.
async function readMessages(file: string): Promise<Messages> {
  const loaded = record(await import(pathToFileURL(file).href));
  const messages = record(loaded['messages'] ?? record(loaded['default'])['messages']);
  const entries = Object.entries(messages);
  assert(entries.length > 0, `${file} holds messages`);
  assert(entries.length <= CATALOG_BUNDLE_LIMITS.messagesMax, `${file} holds too many messages`);
  return new Map(entries.map(([key, value]) => [key, message(value)]));
}

// Only what JSON carries exactly may be inlined; anything else would change in the merge.
function message(value: unknown): unknown {
  if (typeof value === 'string') {
    return value;
  }
  return Object.fromEntries(Object.entries(record(value)).map(([form, text]) => [form, string(text, CATALOG_BUNDLE_LIMITS.bundleCharsMax)]));
}

function assert(condition: boolean, text: string): asserts condition {
  if (!condition) {
    throw new Error(`Assertion failed: ${text}`);
  }
}
