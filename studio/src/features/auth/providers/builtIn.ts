// Goal: what core hands a built-in provider, and how the build selects one. Built-in providers are Studio's own code, so
// unlike a custom provider's factory they receive the session secret, but only to derive per-sign-in values from it (the
// PKCE verifier and nonce, `flowValue` in oidcFlow.ts); they never sign a session, which only core does.
import type { AuthProvider } from '../authProvider';
import type { AuthEnvironment, BuiltInProviderId } from './authConfig';
import type { Fetcher } from './boundedFetch';
import type { PasskeyStore } from './passkeyStore';
import type { RolesSource } from './rolesSource';

export interface BuiltInContext {
  readonly origin: string;
  readonly sessionSecret: string;
  /** Worker vars and secrets minus core credentials (`providerEnvironment`). */
  readonly environment: AuthEnvironment;
  readonly roles: RolesSource;
  readonly fetcher: Fetcher;
  readonly now: () => number;
  /** Present for the passkey provider: the Durable Object's storage, or a Worker-side view of it. */
  readonly passkeys: PasskeyStore | undefined;
}

export type BuiltInFactory = (context: BuiltInContext) => AuthProvider;

/** Generated by scripts/authProviderSlot.ts into src/cloudflare/builtInProviderSlot.ts: only the chosen provider is imported. */
export interface BuiltInSlot {
  readonly id: BuiltInProviderId;
  /** Absent for `github`, which core builds itself. */
  readonly create: BuiltInFactory | undefined;
}
